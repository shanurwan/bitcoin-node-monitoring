#!/usr/bin/env python3
"""Generate the SLO rules, the Kubernetes PrometheusRule and the Grafana dashboard.

Run from the repository root:  python3 scripts/generate.py
CI runs it and fails if the committed files differ from its output.
Standard library only.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNBOOKS = "https://github.com/shanurwan/bitcoin-node-monitoring/blob/main/runbooks/"

# --- SLOs -----------------------------------------------------------------------
# objective: fraction of requests that must be good over 30 days.
# total / good are PromQL with a [W] placeholder for the window.
SLOS = [
    {
        "slo": "rest-availability",
        "alert": "ElectrsRESTAvailability",
        "runbook": "electrs-rest-availability-slo.md",
        "objective": 0.995,
        "what": "REST requests that did not return a 5xx status",
        "total": 'sum by (node) (rate(rest_request_duration_seconds_count{job="electrs"}[W]))',
        "good": 'sum by (node) (rate(rest_request_duration_seconds_count{job="electrs", status!~"5.."}[W]))',
    },
    {
        "slo": "rest-latency",
        "alert": "ElectrsRESTLatency",
        "runbook": "electrs-rest-latency-slo.md",
        "objective": 0.99,
        "what": "REST requests served within 1 s",
        # Prometheus 3 normalises le="1" to "1.0" on ingestion; match both.
        "total": 'sum by (node) (rate(rest_request_duration_seconds_count{job="electrs"}[W]))',
        "good": 'sum by (node) (rate(rest_request_duration_seconds_bucket{job="electrs", le=~"1|1\\\\.0"}[W]))',
    },
    {
        "slo": "electrum-latency",
        "alert": "ElectrsElectrumLatency",
        "runbook": "electrs-electrum-latency-slo.md",
        "objective": 0.99,
        "what": "Electrum RPC calls served within 2.5 s",
        "total": 'sum by (node) (rate(electrum_rpc_count{job="electrs"}[W]))',
        "good": 'sum by (node) (rate(electrum_rpc_bucket{job="electrs", le="2.5"}[W]))',
    },
]
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]
# Burn-rate pairs from the Google SRE workbook (chapter "Alerting on SLOs").
FAST = [("1h", "5m", 14.4), ("6h", "30m", 6)]
SLOW = [("1d", "2h", 3), ("3d", "6h", 1)]
# Below one request per minute the ratios are too noisy to page on.
MIN_RPS = "(1 / 60)"


def q(s):
    """Quote a string for YAML (double quotes, JSON escaping is valid YAML)."""
    return json.dumps(s)


def slo_rules():
    out = [
        "# Generated by scripts/generate.py. Edit SLOS there, not this file.",
        "#",
        "# Multi-window, multi-burn-rate alerts (Google SRE workbook). Each SLO records",
        "#   node:electrs_slo_requests:rate<W>     requests per second",
        "#   node:electrs_slo_errors:ratio_rate<W>  fraction of requests that were bad",
        "# with an slo label, for the windows " + ", ".join(WINDOWS) + ".",
        "groups:",
        "  - name: electrs-slo.rules",
        "    rules:",
    ]
    for s in SLOS:
        for w in WINDOWS:
            total = s["total"].replace("[W]", "[%s]" % w)
            good = s["good"].replace("[W]", "[%s]" % w)
            out += [
                "      - record: node:electrs_slo_requests:rate%s" % w,
                "        expr: %s" % q(total),
                "        labels:",
                "          slo: %s" % s["slo"],
                "      - record: node:electrs_slo_errors:ratio_rate%s" % w,
                "        expr: %s" % q("1 - (%s) / (%s)" % (good, total)),
                "        labels:",
                "          slo: %s" % s["slo"],
            ]
    out += ["", "  - name: electrs-slo.alerts", "    rules:"]
    for s in SLOS:
        budget = round(1 - s["objective"], 6)
        sel = '{slo="%s"}' % s["slo"]

        def cond(pairs):
            parts = []
            for long_w, short_w, factor in pairs:
                thr = "%g * %g" % (factor, budget)
                parts.append(
                    "(node:electrs_slo_errors:ratio_rate%s%s > (%s) and node:electrs_slo_errors:ratio_rate%s%s > (%s))"
                    % (long_w, sel, thr, short_w, sel, thr)
                )
            return " or ".join(parts)

        for kind, pairs, guard_w, sev, for_, horizon in (
            ("Fast", FAST, "1h", "critical", "2m", "2 to 5 days"),
            ("Slow", SLOW, "1d", "warning", "15m", "10 to 30 days"),
        ):
            expr = "(%s) and on (node) node:electrs_slo_requests:rate%s%s > %s" % (
                cond(pairs), guard_w, sel, MIN_RPS)
            out += [
                "      - alert: %sBurn%s" % (s["alert"], kind),
                "        expr: %s" % q(expr),
                "        for: %s" % for_,
                "        labels:",
                "          severity: %s" % sev,
                "          slo: %s" % s["slo"],
                "        annotations:",
                "          summary: %s" % q("electrs %s SLO on {{ $labels.node }} is burning its error budget (%s)"
                                           % (s["slo"], kind.lower())),
                "          description: %s" % q(
                    "Objective: %g%% of %s over 30 days. At the current rate the error budget would be "
                    "gone within %s." % (s["objective"] * 100, s["what"], horizon)),
                "          runbook_url: %s" % (RUNBOOKS + s["runbook"]),
            ]
    return "\n".join(out) + "\n"


# --- Kubernetes PrometheusRule -------------------------------------------------------
RULE_FILES = ["rules/bitcoin-node.rules.yml", "rules/bitcoin-node.alerts.yml", "rules/electrs-slo.yml"]


def prometheus_rule(texts):
    out = [
        "# Generated by scripts/generate.py from rules/*.yml. Do not edit.",
        "apiVersion: monitoring.coreos.com/v1",
        "kind: PrometheusRule",
        "metadata:",
        "  name: bitcoin-node",
        "  labels:",
        "    app.kubernetes.io/name: bitcoin-node-monitoring",
        "spec:",
        "  groups:",
    ]
    for text in texts:
        started = False
        for line in text.splitlines():
            if not started:
                if line.strip() == "groups:":
                    started = True
                continue
            out.append(("  " + line) if line else "")
    return "\n".join(out) + "\n"


# --- Grafana dashboard ---------------------------------------------------------------
DS = {"type": "prometheus", "uid": "${datasource}"}
N = 'node=~"$node"'


class Dash:
    def __init__(self):
        self.panels = []
        self.y = 0
        self.x = 0
        self.row_h = 0
        self.next_id = 1

    def _id(self):
        i = self.next_id
        self.next_id += 1
        return i

    def row(self, title):
        self._newline()
        self.panels.append({"type": "row", "title": title, "id": self._id(), "collapsed": False,
                            "gridPos": {"h": 1, "w": 24, "x": 0, "y": self.y}, "panels": []})
        self.y += 1

    def _newline(self):
        if self.x:
            self.y += self.row_h
            self.x = 0
            self.row_h = 0

    def _place(self, w, h):
        if self.x + w > 24:
            self._newline()
        pos = {"h": h, "w": w, "x": self.x, "y": self.y}
        self.x += w
        self.row_h = max(self.row_h, h)
        return pos

    def _targets(self, exprs):
        return [{"datasource": DS, "expr": e, "legendFormat": leg, "refId": chr(65 + i)}
                for i, (e, leg) in enumerate(exprs)]

    def stat(self, title, exprs, unit="none", w=4, h=4, thresholds=None, description=""):
        steps = thresholds or [{"color": "green", "value": None}]
        self.panels.append({
            "type": "stat", "title": title, "id": self._id(), "datasource": DS, "description": description,
            "gridPos": self._place(w, h), "targets": self._targets(exprs),
            "fieldConfig": {"defaults": {"unit": unit, "thresholds": {"mode": "absolute", "steps": steps}},
                            "overrides": []},
            "options": {"reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": False},
                        "colorMode": "value", "graphMode": "area", "textMode": "auto"},
        })

    def ts(self, title, exprs, unit="none", w=12, h=8, description="", stack=False):
        self.panels.append({
            "type": "timeseries", "title": title, "id": self._id(), "datasource": DS, "description": description,
            "gridPos": self._place(w, h), "targets": self._targets(exprs),
            "fieldConfig": {"defaults": {"unit": unit, "custom": {
                "drawStyle": "line", "lineWidth": 1, "fillOpacity": 10, "showPoints": "never",
                "stacking": {"mode": "normal" if stack else "none", "group": "A"}}}, "overrides": []},
            "options": {"legend": {"displayMode": "list", "placement": "bottom", "showLegend": True},
                        "tooltip": {"mode": "multi", "sort": "desc"}},
        })


def dashboard():
    d = Dash()
    red_at = lambda v: [{"color": "green", "value": None}, {"color": "red", "value": v}]

    d.row("Overview")
    d.stat("bitcoind height", [('max by (node) (bitcoind_blocks{%s})' % N, "{{node}}")])
    d.stat("electrs tip", [('max by (node) (tip_height{job="electrs", %s})' % N, "{{node}}")],
           description="0 until electrs finishes its initial sync.")
    d.stat("Index lag (blocks)", [('node:electrs_index_lag_blocks{%s}' % N, "{{node}}")], thresholds=red_at(4))
    d.stat("Best block age", [('node:bitcoind_tip_age_seconds{%s}' % N, "{{node}}")], unit="s",
           thresholds=red_at(5400), description="From the block header timestamp, which can be off by up to 2 h.")
    d.stat("Peers (in / out)", [('sum by (node, direction) (bitcoind_peers{%s})' % N, "{{direction}}")])
    d.stat("Firing alerts", [('count(ALERTS{alertstate="firing", %s}) or vector(0)' % N, "firing")],
           thresholds=red_at(1))

    d.row("Chain")
    d.ts("Height: bitcoind blocks, headers, electrs tip", [
        ('max by (node) (bitcoind_headers{%s})' % N, "{{node}} headers"),
        ('max by (node) (bitcoind_blocks{%s})' % N, "{{node}} blocks"),
        ('max by (node) (tip_height{job="electrs", %s} > 0)' % N, "{{node}} electrs tip"),
    ])
    d.ts("electrs initial sync", [
        ('max by (node) (initial_sync_height{job="electrs", %s})' % N, "{{node}} last batch height"),
    ], description="Height of the last block batch indexed. With --blocks-dir the RPC fallback indexes "
                   "deferred low-height blocks last, so this can end below the tip.")
    d.ts("Chain tips by status", [('sum by (status) (bitcoind_chain_tips{%s})' % N, "{{status}}")],
         description="valid-fork grows with reorgs and stale blocks seen.")
    d.ts("Best block age", [('node:bitcoind_tip_age_seconds{%s}' % N, "{{node}}")], unit="s")

    d.row("bitcoind")
    d.ts("Peers", [('sum by (node, direction) (bitcoind_peers{%s})' % N, "{{node}} {{direction}}")])
    d.ts("Mempool", [('bitcoind_mempool_usage_bytes{%s}' % N, "{{node}} usage"),
                     ('bitcoind_mempool_max_bytes{%s}' % N, "{{node}} limit")], unit="bytes")
    d.ts("Mempool transactions", [('bitcoind_mempool_transactions{%s}' % N, "{{node}} bitcoind"),
                                  ('mempool_count{job="electrs", type="txs", %s}' % N, "{{node}} electrs")])
    d.ts("RPC: active commands and exporter scrape time", [
        ('bitcoind_rpc_active_commands{%s}' % N, "{{node}} active RPC"),
        ('bitcoind_exporter_scrape_duration_seconds{%s}' % N, "{{node}} scrape seconds"),
    ])

    d.row("electrs serving")
    d.ts("REST requests by status", [('sum by (status) (rate(rest_request_duration_seconds_count{job="electrs", %s}[5m]))' % N,
                                      "{{status}}")], unit="reqps", stack=True)
    d.ts("REST latency", [
        ('histogram_quantile(0.5, sum by (le) (rate(rest_request_duration_seconds_bucket{job="electrs", %s}[5m])))' % N, "p50"),
        ('histogram_quantile(0.99, sum by (le) (rate(rest_request_duration_seconds_bucket{job="electrs", %s}[5m])))' % N, "p99"),
    ], unit="s")
    d.ts("Electrum calls by method (top 10)", [
        ('topk(10, sum by (method) (rate(electrum_rpc_count{job="electrs", %s}[5m])))' % N, "{{method}}")],
        unit="reqps")
    d.ts("Electrum latency p99 by method (top 10)", [
        ('topk(10, histogram_quantile(0.99, sum by (method, le) (rate(electrum_rpc_bucket{job="electrs", %s}[5m]))))' % N,
         "{{method}}")], unit="s")
    d.ts("Electrum clients and subscriptions", [
        ('electrum_clients{job="electrs", %s}' % N, "{{node}} clients"),
        ('electrum_subscriptions{job="electrs", %s}' % N, "{{node}} subscriptions"),
    ])
    d.ts("SLO error ratio (1h window)", [
        ('node:electrs_slo_errors:ratio_rate1h{%s}' % N, "{{node}} {{slo}}")], unit="percentunit",
        description="Budgets: rest-availability 0.5%, rest-latency 1%, electrum-latency 1%. "
                    "The fast-burn alert fires at 14.4x the budget over 1 h.")

    d.row("electrs and bitcoind RPC")
    d.ts("bitcoind RPC p99 by method", [
        ('histogram_quantile(0.99, sum by (method, le) (rate(daemon_rpc_bucket{job="electrs", %s}[5m])))' % N,
         "{{method}}")], unit="s")
    d.ts("RPC connection handshakes and proxied calls", [
        ('sum by (result) (rate(daemon_rpc_conn_handshake{job="electrs", %s}[5m]))' % N, "handshake {{result}}"),
        ('sum by (result) (rate(daemon_rpc_proxied{job="electrs", %s}[5m]))' % N, "proxied {{result}}"),
    ], unit="ops")

    d.row("electrs memory and storage")
    d.ts("electrs memory", [
        ('process_memory_rss{job="electrs", %s}' % N, "{{node}} RSS"),
        ('bitcoin_node:electrs_memory_budget_bytes', "budget"),
        ('node:electrs_rocksdb_table_readers_bytes:sum{%s}' % N, "{{node}} RocksDB table readers"),
        ('sum by (node) (rocksdb_cur_size_all_mem_tables_bytes{job="electrs", %s})' % N, "{{node}} memtables"),
        ('sum by (node) (rocksdb_block_cache_usage_bytes{job="electrs", %s})' % N, "{{node}} block cache"),
    ], unit="bytes", description="Table-reader memory grows with the database unless "
                                 "--cache-index-filter-blocks is set.")
    d.ts("RocksDB SST size by database", [
        ('sum by (db) (rocksdb_total_sst_files_size_bytes{job="electrs", %s})' % N, "{{db}}")],
        unit="bytes", stack=True)
    d.ts("RocksDB compaction", [
        ('sum by (db) (rocksdb_estimate_pending_compaction_bytes{job="electrs", %s})' % N, "{{db}} pending bytes"),
    ], unit="bytes")
    d.ts("RocksDB running compactions and write stops", [
        ('sum by (db) (rocksdb_num_running_compactions{job="electrs", %s})' % N, "{{db}} compactions"),
        ('sum by (db) (rocksdb_is_write_stopped{job="electrs", %s})' % N, "{{db}} write stopped"),
    ])

    d.row("Host")
    d.ts("Free space on data filesystems", [
        ('node_filesystem_avail_bytes{job="node", fstype!~"tmpfs|ramfs|overlay|squashfs", %s}' % N,
         "{{node}} {{mountpoint}}")], unit="bytes")
    d.ts("bitcoind blocks and electrs database size", [
        ('bitcoind_size_on_disk_bytes{%s}' % N, "{{node}} bitcoind blocks"),
        ('node:electrs_rocksdb_sst_bytes:sum{%s}' % N, "{{node}} electrs SST"),
    ], unit="bytes")

    return {
        "title": "Bitcoin node: bitcoind + electrs",
        "uid": "bitcoin-node",
        "description": "bitcoind and electrs health, serving SLOs and storage. From bitcoin-node-monitoring.",
        "tags": ["bitcoin", "electrs", "bitcoind"],
        "timezone": "utc",
        "schemaVersion": 39,
        "version": 1,
        "editable": True,
        "graphTooltip": 1,
        "refresh": "30s",
        "time": {"from": "now-6h", "to": "now"},
        "templating": {"list": [
            {"name": "datasource", "type": "datasource", "query": "prometheus", "label": "Data source",
             "current": {}, "hide": 0, "refresh": 1},
            {"name": "node", "type": "query", "label": "Node", "datasource": DS,
             "query": {"query": 'label_values(up{job=~"bitcoind|electrs"}, node)', "refId": "node"},
             "definition": 'label_values(up{job=~"bitcoind|electrs"}, node)',
             "includeAll": True, "multi": True, "allValue": ".*", "current": {}, "refresh": 2, "sort": 1,
             "hide": 0},
        ]},
        "annotations": {"list": []},
        "links": [],
        "panels": d.panels,
    }


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", newline="\n") as f:
        f.write(text)


def main():
    write("rules/electrs-slo.yml", slo_rules())
    texts = []
    for p in RULE_FILES:
        with open(os.path.join(ROOT, p)) as f:
            texts.append(f.read())
    write("kubernetes/base/prometheusrule.yaml", prometheus_rule(texts))
    dash = json.dumps(dashboard(), indent=2, sort_keys=True) + "\n"
    write("dashboards/bitcoin-node.json", dash)
    write("kubernetes/base/bitcoin-node-dashboard.json", dash)
    # Kustomize only reads files inside the kustomization directory.
    with open(os.path.join(ROOT, "exporter/bitcoind_exporter.py")) as f:
        write("kubernetes/exporter/bitcoind_exporter.py", f.read())


if __name__ == "__main__":
    main()
